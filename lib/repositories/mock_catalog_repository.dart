  @override
  PricingQuotePreview buildPreviewQuote({
    required Accommodation category,
    required RatePlanModel ratePlan,
    required DateTime checkInDate,
    required DateTime checkOutDate,
    int roomsCount = 1,
    String? promoCode,
  }) {
    final nights = checkOutDate.difference(checkInDate).inDays.clamp(1, 90);
    final baseNightly = category.pricePerNight;
    final grossTotal = baseNightly * nights * roomsCount;

    // Preview estimate only — clearly marked as a preview until Laravel PricingEngineService responds
    double discountPercent = ratePlan.previewDiscountPercent;
    String? appliedPromo;
    if (promoCode != null && promoCode.trim().isNotEmpty) {
      appliedPromo = promoCode.trim().toUpperCase();
    }

    final discountAmount = double.parse(
      (grossTotal * (discountPercent / 100.0)).toStringAsFixed(2),
    );
    final totalPayable = double.parse(
      (grossTotal - discountAmount).toStringAsFixed(2),
    );
    final effectiveNightly = double.parse(
      (totalPayable / (nights * roomsCount)).toStringAsFixed(2),
    );

    return PricingQuotePreview(
      roomCategoryId: category.id,
      roomCategoryName: category.title,
      ratePlanCode: ratePlan.code,
      ratePlanName: ratePlan.name,
      checkInDate: checkInDate,
      checkOutDate: checkOutDate,
      nights: nights,
      roomsCount: roomsCount,
      baseNightlyRatePgk: baseNightly,
      effectiveNightlyRatePgk: effectiveNightly,
      grossTotalPgk: grossTotal,
      discountAmountPgk: discountAmount,
      totalPayablePgk: totalPayable,
      promoCodeApplied: appliedPromo,
      gstInclusive: true,
      isPreviewEstimate: true,
      pricingNotice:
          'Official Nightly Quote (GST-Inclusive · Nightly Only). Full payment required prior to confirmation. Cancellation >=48h: 70% refund; <48h or no-show: 0% refund. Bookings are non-transferable.',
    );
  }
